# ---------------------------------------------------------------- 核心复现
def parse_payload(data: bytes) -> dict:
    """解析 blackBox 密文前的 protobuf 风格 payload (与 JS QOoQQQ 组装结果一致)。

    field1: tag 0x08 varint(4=version)
    field2: tag 0x12 字节数组 (AES 密文)
    field3: tag 0x1a 48B (13B 头部 + 35B key 区域)
    field4: tag 0x22 16B
    """
    fields, i = {}, 0
    while i < len(data):
        tag = data[i]; i += 1
        wt, fn = tag & 7, tag >> 3
        v = 0; shift = 0
        while True:                       # varint 长度/值
            x = data[i]; i += 1
            v |= (x & 0x7f) << shift; shift += 7
            if not x & 0x80:
                break
        if wt == 2:
            fields[fn] = data[i:i + v]; i += v
        else:
            fields[fn] = v
    return fields


def recover_session_key(payload: bytes) -> str:
    """反推 35 字符会话 key: field3[13:48] XOR P_35, 校验全部落在字母表内。"""
    fields = parse_payload(payload)
    tail = fields[3][HEAD_LEN:HEAD_LEN + 35]
    key = "".join(chr(b ^ p) for b, p in zip(tail, P_35))
    assert len(key) == 35 and all(c in ALPHABET for c in key), \
        "key 未通过 62 字符字母表校验: " + key
    return key


def derive_key_from_random(f64s: list) -> str:
    """JS→Python 对照: wasm func 193 的 key 派生循环。

    JS: key[i] = alphabet[Math.trunc(f64[i] * 62) % 62]
    固定 Math.random=0.5 -> trunc(31) % 62 = 31 -> alphabet[31] = 's'
    """
    return "".join(ALPHABET[int(x * 62) % 62] for x in f64s)


